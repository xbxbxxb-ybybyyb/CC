def get_desample_minute_dict(period):

    if 240 % period != 0:
        raise ValueError("Period must divide 240 exactly")
    _trade_minutes = trade_minutes[1:-1]
    desample_minutes = [_trade_minutes[0]]
    desample_minutes += sorted(_trade_minutes[0::period] * period)
    desample_minutes += [desample_minutes[-1]]
    desample_minutes = [trade_minutes[(trade_minutes.index(x) + period)] for x in desample_minutes]
    desample_minute_dict = dict(zip(trade_minutes, desample_minutes))
    return desample_minute_dict

def get_desample_minute_panel(df, period, method):

    df.index.names = ['date', 'time']
    _df = df.copy().reset_index()
    _df['time'] = _df['time'].map(get_desample_minute_dict(period))
    _df = _df.groupby(['date', 'time']).agg(method) if method != 'sum' else _df.groupby(
        ['date', 'time']).sum(min_count=1)
    _df = _df.reset_index().set_index(['date', 'time'])
    _df = _df.convert_objects()
    return _df
