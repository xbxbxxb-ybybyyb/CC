def search_index(x, y):

    index = np.argsort(x)
    sorted_x = x[index]
    sorted_index = np.searchsorted(sorted_x, y)
    y_index = np.take(index, sorted_index, mode="clip")
    mask = x[y_index] != y
    result = np.ma.array(y_index, mask=mask, fill_value=0)
    return result

class TickDataPrepare(object):

    def __init__(self, address='/arch1/group/800442/800319/LimitTickData2/'):

        idx_date = np.load(f'{address}/LowFreqData/idx_date.npy').tolist()
        idx_code = np.load(f'{address}/LowFreqData/idx_code.npy').tolist()
        idx_tick = common_ticks

        self.idx_date = idx_date
        self.idx_code = idx_code
        self.idx_tick = idx_tick
        self.address = address

    def _get_tick_1factor(self, item, dc_idx, time_idx):

        dtype = format_dict[item]
        _dc_idx = list(dc_idx)
        _time_idx = list(time_idx)
        dc_idx = sorted(_dc_idx)
        time_idx = sorted(_time_idx)
        if _dc_idx != dc_idx:
            raise ValueError("date code idx list must be sorted firstly.")
        if _time_idx != time_idx:
            raise ValueError("tick list idx must be sorted firstly.")
        dc_max = dc_idx[-1]

        if dc_idx[-1] - dc_idx[0] + 1 == len(dc_idx):
            dc_idx = slice(dc_idx[0], dc_idx[-1] + 1)
        if time_idx[-1] - time_idx[0] + 1 == len(time_idx):
            time_idx = slice(time_idx[0], time_idx[-1] + 1)

        factor = np.memmap('%s/%s.npy' % (self.address, item),
                           dtype=dtype, mode='r', shape=(dc_max + 1, 5000), offset=128)
        factor = factor[dc_idx, time_idx]
        return factor

    def get_data_by_date_list(self, item: object, start_date: object = None, end_date: object = None,
                              date_list: object = None,
                              start_tick: object = 91500, end_tick: object = 150000, tick_list: object = None,
                              return_idx: object = False) -> object:
        """

        :rtype: 
        """
        if date_list:
            _date_list = sorted(date_list)
            if _date_list != date_list:
                raise ValueError("date list must be sorted firstly.")
        else:
            date_list = get_date_range(start_date, end_date)

        dt_choose = np.asanyarray([(x in date_list) for x in self.idx_date])
        idx_date = np.asanyarray(self.idx_date)[dt_choose]
        idx_code = np.asanyarray(self.idx_code)[dt_choose]
        _dc = np.arange(len(self.idx_date))[dt_choose]

        if tick_list:
            _tick_list = sorted(tick_list)
            if _tick_list != tick_list:
                raise ValueError("tick list must be sorted firstly.")
        else:
            tick_list = [x for x in self.idx_tick if (x >= start_tick) & (x <= end_tick)]

        tick_choose = np.asanyarray([(x in tick_list) for x in self.idx_tick])
        idx_tick = np.asanyarray(self.idx_tick)[tick_choose]
        _tick = np.arange(len(self.idx_tick))[tick_choose]

        factor = self._get_tick_1factor(item, _dc, _tick)

        if return_idx:
            return pd.DataFrame(factor, index=pd.MultiIndex.from_arrays(
                [idx_date, idx_code], names=['date', 'code']), columns=idx_tick)
        else:
            return factor

    def get_data_by_date_code_tuple(self, item, dc_tuple_list, start_tick=91500,
                                    end_tick=150000, tick_list=None, return_idx=False):

        _dc_tuple_list = sorted(dc_tuple_list)
        if _dc_tuple_list != dc_tuple_list:
            raise ValueError("dc_tuple_list must be sorted firstly.")

        self_date_code = pd.MultiIndex.from_arrays([self.idx_date, self.idx_code]).values
        dc_tuple_list = pd.MultiIndex.from_tuples(dc_tuple_list).values
        _dc = search_index(self_date_code, dc_tuple_list)
        _dc = _dc.data[~_dc.mask].tolist()
        idx_date_code = np.asanyarray(self_date_code)[_dc].tolist()

        if tick_list:
            _tick_list = sorted(tick_list)
            if _tick_list != tick_list:
                raise ValueError("tick list must be sorted firstly.")
        else:
            tick_list = [x for x in self.idx_tick if (x >= start_tick) & (x <= end_tick)]

        tick_choose = np.asanyarray([(x in tick_list) for x in self.idx_tick])
        idx_tick = np.asanyarray(self.idx_tick)[tick_choose]
        _tick = np.arange(len(self.idx_tick))[tick_choose]

        factor = self._get_tick_1factor(item, _dc, _tick)

        if return_idx:
            return pd.DataFrame(factor, index=pd.MultiIndex.from_tuples(idx_date_code, names=['date', 'code']),
                                columns=idx_tick)
        else:
            return factor


